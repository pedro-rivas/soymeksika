export type AirportPoint = {
  code: string;
  lngLat: [number, number];
};

export function resolveAirports(codes: string[]): AirportPoint[] {
  const points: AirportPoint[] = [];
  for (const raw of codes) {
    const code = raw.trim().toUpperCase();
    if (!code) continue;
    const lngLat = AIRPORT_COORDS[code];
    if (!lngLat) continue;
    if (points.length && points[points.length - 1].code === code) continue;
    points.push({ code, lngLat });
  }
  return points;
}
